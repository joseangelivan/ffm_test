-- src/lib/sql/system/sessions_schema.sql

-- Drop the old table if it exists to ensure a clean slate, especially for type changes.
DROP TABLE IF EXISTS sessions;

CREATE TABLE IF NOT EXISTS sessions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(50) NOT NULL,
    user_type VARCHAR(20) NOT NULL,
    token TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Unique index to prevent duplicate sessions for the same user type
CREATE UNIQUE INDEX IF NOT EXISTS sessions_user_type_unique_idx ON sessions(user_id, user_type);
-- Index on token for faster lookups during logout/verification
CREATE INDEX IF NOT EXISTS sessions_token_idx ON sessions(token);
-- Index on expiration for cleaning up old sessions
CREATE INDEX IF NOT EXISTS sessions_expires_at_idx ON sessions(expires_at);

-- Trigger to automatically update the 'updated_at' timestamp
CREATE OR REPLACE TRIGGER set_timestamp
BEFORE UPDATE ON sessions
FOR EACH ROW
EXECUTE FUNCTION trigger_set_timestamp();
