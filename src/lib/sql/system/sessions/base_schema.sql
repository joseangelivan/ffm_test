-- Tabla para almacenar sesiones de usuario activas
CREATE TABLE IF NOT EXISTS public.sessions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(50) NOT NULL,
    user_type VARCHAR(20) NOT NULL CHECK (user_type IN ('admin', 'resident', 'gatekeeper')),
    token TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índices para mejorar el rendimiento de las consultas
CREATE INDEX IF NOT EXISTS idx_sessions_user_id_type ON public.sessions (user_id, user_type);
CREATE INDEX IF NOT EXISTS idx_sessions_token ON public.sessions (token);
CREATE INDEX IF NOT EXISTS idx_sessions_expires_at ON public.sessions (expires_at);

-- Disparador para actualizar automáticamente el campo updated_at
DROP TRIGGER IF EXISTS set_timestamp ON public.sessions;
CREATE TRIGGER set_timestamp
BEFORE UPDATE ON public.sessions
FOR EACH ROW
EXECUTE PROCEDURE trigger_set_timestamp();
